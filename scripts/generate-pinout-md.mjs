// Generates a full markdown table of each STM32F446 package pinout (plus the
// Nucleo-F446RE board mapping for the LQFP64), straight from the canonical
// docs/public/pinout/<package>/pins.json so the tables can never drift from
// what the interactive component renders.
//
//   node scripts/generate-pinout-md.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");

const PACKAGES = [
  {
    id: "LQFP64",
    chip: "STM32F446RE",
    board: "Nucleo-F446RE",
    out: "tools/pinout-table.md",
    sources: "ST `DS10693 Rev 10` (STM32F446xC/E datasheet) and `UM1724 Rev 16`\n> (Nucleo user manual)",
  },
  {
    id: "LQFP100",
    chip: "STM32F446VE",
    board: null,
    out: "tools/pinout-table-lqfp100.md",
    sources: "ST `DS10693 Rev 10` (STM32F446xC/E datasheet), Table 10",
  },
];

const io = (p) => {
  const meaning = {
    FT: "5V-tolerant I/O",
    FTf: "5V-tolerant I/O (FM+)",
    TTa: "ADC I/O",
    B: "BOOT0",
    RST: "reset",
    S: "supply",
  };
  return p.io === "S" ? "S" : `${p.io} · ${meaning[p.io] ?? p.io}`;
};

const arduino = (p) =>
  p.arduino.map((a) => `${a.pin}${a.func ? ` (${a.func})` : ""}`).join("<br>") || "—";

const morpho = (p) =>
  p.morpho.map((m) => `${m.conn}-${m.pin}`).join("<br>") || "—";

const esc = (s) => String(s).replace(/\|/g, "\\|");

const notes = (p) =>
  [p.maxSpeed && `max ${p.maxSpeed}`, ...(p.remarks ?? [])].filter(Boolean).map(esc).join("<br>") || "—";

for (const pkg of PACKAGES) {
  const pins = JSON.parse(
    readFileSync(join(root, "docs/public/pinout", pkg.id, "pins.json"), "utf8")
  );

  const rows = pins.map((p) => {
    const type = p.type === "I/O" ? `${p.type} · ${io(p)}` : p.type;
    return [
      `**${p.num}**`,
      `\`${p.fullName ?? p.name}\``,
      type,
      esc(p.signal || "—"),
      esc(p.alt.join(", ") || "—"),
      esc(p.extra.join(", ") || "—"),
      ...(pkg.board ? [arduino(p), morpho(p)] : []),
      notes(p),
    ];
  });

  const head = [
    "#",
    "Pin",
    "Type",
    "Default function",
    "Alternate functions",
    "Additional functions",
    ...(pkg.board ? ["Arduino", "Morpho"] : []),
    "Datasheet notes",
  ];

  const md = [
    "---",
    "# AUTO-GENERATED by scripts/generate-pinout-md.mjs — do not edit by hand.",
    "layout: PinoutLayout",
    "sidebar: false",
    "hero:",
    `  name: ${pkg.chip} (${pkg.id}) pinout`,
    `  tagline: Complete ${pins.length}-pin table — pin number, type, functions${
      pkg.board ? ` and ${pkg.board} board mapping` : ""
    }.`,
    "  actions:",
    "    - text: Interactive pinout",
    "      link: /tools/pinout",
    "      theme: alt",
    "---",
    "",
    `> Source: ${pkg.sources}. ${pins.length}-pin ${pkg.id} package, pin 1 at the`,
    "> top-left corner, numbered counter-clockwise.",
    "",
    "**Alternate functions** are selected through the `GPIOx_AFR` registers;",
    "**additional functions** are enabled directly through peripheral registers",
    "(ADC, DAC, oscillator, wake-up, …).",
    ...(pkg.board
      ? [`**Arduino** and **Morpho** columns give the ${pkg.board} header pin names.`]
      : []),
    "Peripheral bus speeds are in `docs/public/pinout/buses.json`.",
    "",
    "| " + head.join(" | ") + " |",
    "|" + head.map(() => "---").join("|") + "|",
    ...rows.map((r) => "| " + r.join(" | ") + " |"),
    "",
  ].join("\n");

  const out = join(root, "docs", pkg.out);
  writeFileSync(out, md + "\n");
  console.log(`Wrote ${pins.length} pins to ${out}`);
}
