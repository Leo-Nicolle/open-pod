// Generates a full markdown table of the STM32F446RE (LQFP64) pinout and its
// Nucleo-F446RE board mapping, straight from the canonical pins.json so the
// table can never drift from what the interactive component renders.
//
//   node scripts/generate-pinout-md.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const pins = JSON.parse(
  readFileSync(join(root, "docs/.vitepress/theme/components/pinmap/pins.json"), "utf8")
);

const io = (p) => {
  const meaning = {
    FT: "5V-tolerant I/O",
    FTf: "5V-tolerant I/O (FM+)",
    TTa: "ADC I/O",
    B: "BOOT0",
    RST: "reset",
    S: "supply",
  };
  return p.io === "S" ? "S" : `${p.io} · ${meaning[p.io] ?? p.io}`;
};

const arduino = (p) =>
  p.arduino.map((a) => `${a.pin}${a.func ? ` (${a.func})` : ""}`).join("<br>") || "—";

const morpho = (p) =>
  p.morpho.map((m) => `${m.conn}-${m.pin}`).join("<br>") || "—";

const esc = (s) => String(s).replace(/\|/g, "\\|");

const rows = pins.map((p) => {
  const type = p.type === "I/O" ? `${p.type} · ${io(p)}` : p.type;
  return [
    `**${p.num}**`,
    `\`${p.fullName ?? p.name}\``,
    type,
    esc(p.signal || "—"),
    esc(p.alt.join(", ") || "—"),
    esc(p.extra.join(", ") || "—"),
    arduino(p),
    morpho(p),
  ];
});

const head = [
  "#",
  "Pin",
  "Type",
  "Default function",
  "Alternate functions",
  "Additional functions",
  "Arduino",
  "Morpho",
];

const md = [
  "---",
  "# AUTO-GENERATED by scripts/generate-pinout-md.mjs — do not edit by hand.",
  "layout: PinoutLayout",
  "hero:",
  "  name: STM32F446RE (LQFP64) pinout",
  "  tagline: Complete 64-pin table — pin number, type, functions and Nucleo-F446RE board mapping.",
  "  actions:",
  "    - text: Interactive pinout",
  "      link: /pinout",
  "      theme: alt",
  "---",
  "",
  "> Source: ST `DS10693 Rev 10` (STM32F446xC/E datasheet) and `UM1724 Rev 16`",
  "> (Nucleo user manual). 64-pin LQFP64 package, pin 1 at the top-left corner,",
  "> numbered counter-clockwise.",
  "",
  "**Alternate functions** are selected through the `GPIOx_AFR` registers;",
  "**additional functions** are enabled directly through peripheral registers",
  "(ADC, DAC, oscillator, wake-up, …). **Arduino** and **Morpho** columns give the",
  "Nucleo-F446RE header pin names.",
  "",
  "| " + head.join(" | ") + " |",
  "|" + head.map(() => "---").join("|") + "|",
  ...rows.map((r) => "| " + r.join(" | ") + " |"),
  "",
].join("\n");

const out = join(root, "docs", "pinout-table.md");
writeFileSync(out, md + "\n");
console.log(`Wrote ${pins.length} pins to ${out}`);
